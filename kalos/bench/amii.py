"""Pool-replay benchmark on the six published cell-culture media datasets.

Source: Parsaee et al., "A data-driven evaluation of optimization techniques in
cell culture media" (Bioinformatics 2026), code CC BY 4.0, datasets
https://github.com/Amii-Applied-AI/amii-cell-ag-tools (active-learning-for-cell-media/Data).

The CSVs are NOT redistributed here: the repo's Data/SOURCES.md says the CC BY
licence covers the code only and the datasets stay under their original
publications' terms. Point `KALOS_AMII_DATA` (or `KALOS_MEDIA_DATA`) at the
folder that holds them; nothing is read from, or copied into, this repository.

What this is and is not:
  - It is a "hide-the-label" pool replay on the RAW measured rows: the optimizer
    only ever sees labels it has already revealed (verified by a fit-spy test).
  - It is NOT the paper's protocol. The paper scores optimizers on landscapes
    generated by a surrogate (GP/RF/NN/BNN) fitted to these data; here the pool
    labels are the measurements themselves.
  - The objectives are cell growth / absorbance / fold-change, not product titer.
  - The BO arm is "pool EI (top-q)": analytic EI on a discrete pool with the best
    observed (noisy) value as incumbent, top-q picks, no joint batch. It is NOT the
    qLogNEI optimizer in kalos.core.optimize, so it says nothing about that code path.
  - The pools were produced by earlier optimisation / active-learning campaigns, so they
    are enriched for good regions and random sampling is a strong baseline; results do not
    transfer to open design spaces.
  - Datasets with an information-source / fidelity column (e.g. DBO's IS_indicator) mix
    assays; an optimizer can "win" by learning the source, not a better medium. Treat
    such results as unresolved until the data are stratified by source.
  - Evidence standard: compare arms PAIRED per seed (see `paired_comparison`), with >= 20
    seeds and a multiple-comparison correction across datasets x batch sizes. A median
    over a handful of seeds is not evidence.
"""
from __future__ import annotations

import os
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd


@dataclass(frozen=True)
class AmiiDataset:
    name: str
    filename: str
    target: str
    drop: tuple[str, ...] = ()
    features: tuple[str, ...] = ()  # empty = every column not dropped / not a label
    label_cols: tuple[str, ...] = ()
    transform: str | None = None  # "log1p" | "log1p_over_poscont"
    fidelity_col: str | None = None
    objective: str = ""


_T_FEATS = ("bME", "LS1000", "PY", "ITS", "ALB", "MEMAA", "ARG", "GLU", "CB6", "IL-2", "IL-12", "IL-18", "IL-21", "VS")
_TF_FEATS = ("CHIR99021", "SP600125", "Dexameth", "rhGM-CSF", "rhSCF", "rhIGF-1", "AA", "Y27632",
             "ALB", "FN", "GL", "CH", "ITS", "bME", "PY")

# Mirrors the paper repo's utils/datasets.py registry (feature/target choices,
# target transforms). MOBO is multi-fidelity: the registry ignores the Fidelity
# column, which mixes different assays of the same recipe; here the pool keeps the
# highest fidelity only (see load_amii_pool).
REGISTRY: dict[str, AmiiDataset] = {d.name: d for d in (
    AmiiDataset("DBO_rat_myocyte", "DBO_dataset_rat_myocyte.csv", "Label", label_cols=("Label", "Label_var"),
                objective="rat myoblast growth (standardised label)"),
    AmiiDataset("MOBO_rat_myocyte", "MOBO_dataset_rat_myocyte.csv", "Label", drop=("Unnamed: 0", "Fidelity"),
                label_cols=("Label", "Label_var"), fidelity_col="Fidelity",
                objective="rat myoblast growth (standardised label, multi-fidelity)"),
    AmiiDataset("HeLa_regular", "df_Human_Hela_regular_mode.csv", "mean A450", drop=("Unnamed: 0", "Round"),
                label_cols=("mean A450", "sd A450"), objective="HeLa-S3 A450 absorbance"),
    AmiiDataset("HeLa_timesaving", "df_Human_Hela_timesaving_mode.csv", "mean A450", drop=("Unnamed: 0", "Round"),
                label_cols=("mean A450", "sd A450"), objective="HeLa-S3 A450 absorbance (time-saving mode)"),
    AmiiDataset("Tcell_expansion", "df_Human_T_Cell_Expanded.csv", "Cell count", features=_T_FEATS,
                transform="log1p_over_poscont", objective="primary T-cell count, log1p(count / positive control FC)"),
    AmiiDataset("TF1_expansion", "df_Human_TF_Cell_Expanded.csv", "normalized cell count", features=_TF_FEATS,
                transform="log1p", objective="TF-1 normalized cell count, log1p"),
)}


def amii_data_dir(explicit: str | Path | None = None) -> Path | None:
    for cand in (explicit, os.environ.get("KALOS_AMII_DATA"), os.environ.get("KALOS_MEDIA_DATA")):
        if cand:
            p = Path(cand).expanduser().resolve()
            if p.is_dir():
                return p
    return None


def load_amii_pool(name: str, data_dir: str | Path | None = None) -> tuple[np.ndarray, np.ndarray, dict]:
    """(X, y, info) for one dataset. Rows are made finite, constant columns dropped,
    and replicate rows with identical settings averaged. `info` records every count
    so a report can state what was kept."""
    spec = REGISTRY[name]
    root = amii_data_dir(data_dir)
    path = root / spec.filename if root else None
    if path is None or not path.is_file():
        raise FileNotFoundError(
            f"{spec.filename} not found. Set KALOS_AMII_DATA (or KALOS_MEDIA_DATA) to the folder holding the "
            "paper's Data/*.csv; they are not redistributed with kalos."
        )
    df = pd.read_csv(path)
    n_file = len(df)
    if spec.fidelity_col:
        df = df[df[spec.fidelity_col] == df[spec.fidelity_col].max()]
    n_fidelity = len(df)

    y: pd.Series
    if spec.transform == "log1p_over_poscont":
        y = pd.Series(
            np.log1p(pd.to_numeric(df[spec.target], errors="coerce") / pd.to_numeric(df["PosCont FC"], errors="coerce")),
            index=df.index,
        )
    elif spec.transform == "log1p":
        y = pd.Series(np.log1p(pd.to_numeric(df[spec.target], errors="coerce")), index=df.index)
    else:
        y = pd.to_numeric(df[spec.target], errors="coerce")
    cols = list(spec.features) if spec.features else [
        c for c in df.columns if c not in set(spec.drop) | set(spec.label_cols)
    ]
    X = df[cols].apply(pd.to_numeric, errors="coerce")
    keep = np.isfinite(X.to_numpy(float)).all(1) & np.isfinite(y.to_numpy(float))
    X, y = X[keep], y[keep]
    n_finite = len(X)
    nunique = X.nunique()
    X = X.loc[:, nunique > 1]
    agg = X.assign(__y=y.to_numpy()).groupby(list(X.columns), sort=False, as_index=False)["__y"].mean()
    Xa = agg[list(X.columns)].to_numpy(float)
    ya = agg["__y"].to_numpy(float)
    info = {
        "name": name, "file": spec.filename, "objective": spec.objective,
        "rows_in_file": n_file, "rows_after_fidelity": n_fidelity, "rows_finite": n_finite,
        "unique_recipes": int(len(ya)), "n_features": int(Xa.shape[1]), "features": list(X.columns),
        "y_min": float(ya.min()), "y_median": float(np.median(ya)), "y_max": float(ya.max()),
        "measured_or_generated": "measured (published experimental data)",
    }
    return Xa, ya, info


# --- trials ----------------------------------------------------------------- #

def _norm(X: np.ndarray) -> np.ndarray:
    lo, hi = X.min(0), X.max(0)
    return (X - lo) / np.where(hi - lo > 0, hi - lo, 1.0)


def run_trial(
    X: np.ndarray, y: np.ndarray, *, q: int, budget: int, n_init: int = 10, seed: int = 0,
    arms: tuple[str, ...] = ("bo", "random", "lhs"), stats: dict | None = None,
) -> dict[str, list[float]]:
    """One seed. Every arm starts from the SAME `n_init` random rows, then spends
    `budget` further evaluations in batches of `q`. Returns best-so-far after each
    evaluation (length n_init + budget) per arm. BO only fits on revealed labels.
    If `stats` is given, `stats["fit_fallbacks"]` counts BO batches where the GP fit
    failed and a random pick was used instead (so a "BO" curve can be partly random)."""
    import torch
    from scipy.stats import norm, qmc

    from kalos.core.surrogate import FitError, Surrogate

    n = len(y)
    if n < n_init + budget:
        raise ValueError(f"pool of {n} rows cannot support n_init={n_init} + budget={budget}")
    rng = np.random.default_rng(seed)
    torch.manual_seed(seed)
    Xn = _norm(X)
    bounds = np.vstack([np.zeros(X.shape[1]), np.ones(X.shape[1])])
    order = rng.permutation(n)
    init = [int(i) for i in order[:n_init]]

    def curve(ev: list[int]) -> list[float]:
        return [float(v) for v in np.maximum.accumulate(y[ev])]

    out: dict[str, list[float]] = {}
    if stats is not None:
        stats["fit_fallbacks"] = 0
    if "bo" in arms:
        ev = list(init)
        remaining = set(int(i) for i in order[n_init:])
        while len(ev) < n_init + budget:
            take = min(q, n_init + budget - len(ev))
            rem = np.array(sorted(remaining))
            try:
                s = Surrogate().fit(Xn[ev], y[ev], bounds=bounds)  # revealed labels only
                mu, sd = s.posterior(Xn[rem])
                sd = np.maximum(np.asarray(sd, float).reshape(-1), 1e-9)
                z = (np.asarray(mu, float).reshape(-1) - y[ev].max()) / sd
                ei = (np.asarray(mu, float).reshape(-1) - y[ev].max()) * norm.cdf(z) + sd * norm.pdf(z)
                picks = [int(rem[j]) for j in np.argsort(-ei)[:take]]  # top-q EI
            except FitError:
                if stats is not None:
                    stats["fit_fallbacks"] += 1
                picks = [int(i) for i in rng.choice(rem, size=take, replace=False)]
            ev += picks
            remaining -= set(picks)
        out["bo"] = curve(ev)
    if "random" in arms:
        rest = np.random.default_rng(seed + 10_000).permutation(np.array([int(i) for i in order[n_init:]]))
        out["random"] = curve(list(init) + [int(i) for i in rest[:budget]])
    if "lhs" in arms:
        ev = list(init)
        used = set(ev)
        pts = qmc.LatinHypercube(d=X.shape[1], seed=seed + 20_000).random(budget)
        lhs_rng = np.random.default_rng(seed + 30_000)
        for p in pts:
            avail = np.array(sorted(set(range(n)) - used))
            d2 = ((Xn[avail] - p) ** 2).sum(1)
            ties = np.nonzero(d2 <= d2.min() + 1e-12)[0]  # grid-like pools have many exact ties
            j = int(avail[ties[int(lhs_rng.integers(len(ties)))]])
            ev.append(j)
            used.add(j)
        out["lhs"] = curve(ev)
    return out


def runs_to_top(curve: list[float], threshold: float) -> int | None:
    """1-based evaluation count at which best-so-far first reaches `threshold`, else None."""
    hit = np.nonzero(np.asarray(curve) >= threshold)[0]
    return int(hit[0]) + 1 if hit.size else None


def benchmark_dataset(
    X: np.ndarray, y: np.ndarray, *, q: int, budget: int, n_init: int = 10, seeds=range(5), top_frac: float = 0.05,
) -> dict:
    """Median and spread (IQR) of runs-to-reach-top-`top_frac` per arm over seeds.
    Seeds that never reach it within the budget are right-censored and counted in
    `reached`; the median treats them as `n_init + budget + 1` (a lower bound)."""
    seeds = list(seeds)
    if len(seeds) < 5:
        raise ValueError("use at least 5 seeds")
    thr = float(np.quantile(y, 1 - top_frac))
    per: dict[str, list[int | None]] = {}
    fallbacks = 0
    for s in seeds:
        st: dict = {}
        for arm, c in run_trial(X, y, q=q, budget=budget, n_init=n_init, seed=s, stats=st).items():
            per.setdefault(arm, []).append(runs_to_top(c, thr))
        fallbacks += st.get("fit_fallbacks", 0)
    cap = n_init + budget + 1
    res = {}
    for arm, runs in per.items():
        v = np.array([cap if r is None else r for r in runs], float)
        res[arm] = {
            "runs": runs, "reached": int(sum(r is not None for r in runs)), "n_seeds": len(seeds),
            "median": float(np.median(v)), "q25": float(np.quantile(v, 0.25)), "q75": float(np.quantile(v, 0.75)),
        }
    # The initial design is shared by all arms and is a random draw: a seed whose start already
    # holds a target row is decided before any optimizer acts. Report it, and pair on the rest.
    solved_at_start = [i for i, r in enumerate(per[next(iter(per))]) if r is not None and r <= n_init]
    paired = {a: paired_comparison(per["bo"], per[a], cap) for a in per if a != "bo"} if "bo" in per else {}
    return {"threshold": thr, "top_frac": top_frac, "q": q, "budget": budget, "n_init": n_init, "arms": res,
            "censored_value": cap, "seeds_solved_by_start": len(solved_at_start),
            "bo_fit_fallbacks": fallbacks, "paired_vs_bo": paired}


def paired_comparison(bo: list[int | None], other: list[int | None], cap: int) -> dict:
    """Per-seed paired comparison of runs-to-target (None -> `cap`, a right-censored lower bound).
    Counts seeds where BO needed fewer / more / equal evaluations and gives a two-sided exact sign
    test on the non-tied seeds. Apply a multiple-comparison correction (e.g. Holm) across datasets
    and batch sizes before calling anything significant; with few seeds this has almost no power."""
    from scipy.stats import binomtest

    a = np.array([cap if r is None else r for r in bo], float)
    b = np.array([cap if r is None else r for r in other], float)
    wins, losses = int((a < b).sum()), int((a > b).sum())
    n = wins + losses
    p = float(binomtest(wins, n, 0.5).pvalue) if n else 1.0
    return {"bo_fewer": wins, "bo_more": losses, "tied": int((a == b).sum()), "sign_test_p": p}
